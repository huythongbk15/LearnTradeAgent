@dataclass(frozen=True)
class FaultProfile:
    """Deterministic execution-fault injection for one tournament cell.

    Every field is an independent knob; the runner applies the combined
    schedule to the SAME execution path so fault runs measure resilience,
    never a different code path.
    """

    name: str = "none"
    #: Drop every k-th bar from the source frame (data gaps).
    drop_gap_bars_every: int = 0
    #: Number of stale-price windows; each freezes the venue feed for
    #  ``stale_window_bars`` consecutive bars starting at multiples of
    #  ``stale_window_stride``.
    stale_windows: int = 0
    stale_window_bars: int = 5
    stale_window_stride: int = 200
    #: Reject the first N order placements with a broker error.
    reject_first_n_orders: int = 0
    #: Market orders fill only this fraction of the requested amount.
    partial_fill_fraction: float = 1.0
    #: First protective-order cancel is silently missed (cancel race).
    cancel_miss_first: bool = False
    #: Every stop-loss placement fails (protection outage).
    break_protection: bool = False

    def __post_init__(self) -> None:
        if self.drop_gap_bars_every < 0 or self.stale_windows < 0:
            raise ValueError("fault counts must be non-negative")
        if not 0.0 < self.partial_fill_fraction <= 1.0:
            raise ValueError("partial_fill_fraction must be in (0, 1]")
        if self.reject_first_n_orders < 0:
            raise ValueError("reject_first_n_orders must be non-negative")

    @property
    def active(self) -> bool:
        return self != FAULT_NONE


FAULT_NONE = FaultProfile()
FAULT_GAP_EVERY_50 = FaultProfile("gap50", drop_gap_bars_every=50)
FAULT_STALE_FEED = FaultProfile("stale", stale_windows=3)
FAULT_REJECT_FIRST_2 = FaultProfile("reject2", reject_first_n_orders=2)
FAULT_PARTIAL_HALF = FaultProfile("partial_half", partial_fill_fraction=0.5)
FAULT_CANCEL_RACE = FaultProfile("cancel_race", cancel_miss_first=True)
FAULT_PROTECTION_OUTAGE = FaultProfile("protect_outage", break_protection=True)

ALL_FAULT_PROFILES = (
    FAULT_NONE,
    FAULT_GAP_EVERY_50,
    FAULT_STALE_FEED,
    FAULT_REJECT_FIRST_2,
    FAULT_PARTIAL_HALF,
    FAULT_CANCEL_RACE,
    FAULT_PROTECTION_OUTAGE,
)


def apply_faults(simulator: Any, profile: FaultProfile) -> None:
    """Wrap exchange/engine hooks on a constructed simulator (in place).

    Faults are injected at the paper exchange level but designed to flow
    through the canonical lifecycle properly (REJECTED orders, partial fills
    with protective stops, cancel races tracked via lifecycle).
    """
    if not profile.active:
        return

    exchange = simulator.engine.exchange
    from trading_agent.execution.paper_exchange import OrderStatus

    # ── Reject first N orders (market orders filled immediately, limit/stop pending) ────
    if profile.reject_first_n_orders:
        state = {"rejected": 0}
        original_fill_market = exchange._fill_market_order

        def rejecting_fill(order_id: str):
            if state["rejected"] < profile.reject_first_n_orders:
                state["rejected"] += 1
                order = exchange.orders.get(order_id)
                if order:
                    order.status = OrderStatus.REJECTED
                    exchange._save_state()
                return
            return original_fill_market(order_id)

        exchange._fill_market_order = rejecting_fill

    # ── Break protection (stop-loss placement fails) ────────────────────────
    if profile.break_protection:
        original_place = exchange.place_order

        def placing(
            symbol: str,
            side: Any,
            order_type: Any,
            amount: float = 0.0,
            price: float | None = None,
            stop_price: float | None = None,
            idempotency_key: str | None = None,
            client_order_id: str | None = None,
        ):
            order_type_str = str(order_type).lower()
            is_stop = "stop" in order_type_str
            order = original_place(
                symbol=symbol,
                side=side,
                order_type=order_type,
                amount=amount,
                price=price,
                stop_price=stop_price,
                idempotency_key=idempotency_key,
                client_order_id=client_order_id,
            )
            if is_stop:
                # Stop order placed but broker rejects it
                order.status = OrderStatus.REJECTED
                exchange._save_state()
            return order

        exchange.place_order = placing

    # ── Partial fills (market orders only fill fraction) ────────────────────
    # Apply only to BUY (entry) orders — SELL (exit) orders fill fully to
    # avoid residual unprotected positions. This models realistic broker
    # behavior where entry orders are more likely to be partially filled.
    if profile.partial_fill_fraction < 1.0:
        original_fill = exchange._fill_market_order

        def partial_fill(order_id: str):
            order = exchange.orders.get(order_id)
            if order is None:
                return original_fill(order_id)
            # Only partially fill BUY orders (entry); SELL orders fill fully
            # to close positions cleanly and avoid residual unprotected qty.
            from trading_agent.execution.paper_exchange import OrderSide

            if order.side == OrderSide.BUY:
                real_amount = order.amount
                try:
                    order.amount = real_amount * profile.partial_fill_fraction
                    return original_fill(order_id)
                finally:
                    order.amount = real_amount
            return original_fill(order_id)

        exchange._fill_market_order = partial_fill

    # ── Cancel race (first cancel reported as lost by venue) ───────────────
    if profile.cancel_miss_first:
        original_cancel = exchange.cancel_order
        state = {"missed": False}

        def cancelling(order_id: str):
            result = original_cancel(order_id)
            if not state["missed"] and result is not None:
                state["missed"] = True
                order = exchange.orders.get(order_id)
                if order is not None:
                    order.status = OrderStatus.OPEN
                return None
            return result

        exchange.cancel_order = cancelling

    # ── Stale price feed (already works correctly) ─────────────────────────
    if profile.stale_windows:
        original_update = simulator.engine.update_prices

        def stale_update(prices: dict[str, float]):
            now = getattr(rc_clock(), "current", None)
            if now is None:
                return original_update(prices)
            for start in simulator._stale_starts:
                if (
                    start
                    <= now
                    < start + simulator.timeframe_delta * profile.stale_window_bars
                ):
                    return
            return original_update(prices)

        simulator.engine.update_prices = stale_update

    # ── Data gaps: record in manifest, don't drop bars (breaks simulator) ───
    if profile.drop_gap_bars_every:
        pass  # Handled in run_cell() data loading


def rc_clock():
    """Access the simulator's fake clock class (monkeypatched in scripts)."""
    import sys

    module = sys.modules.get("scripts.full_system_backtest")
    if module is None:
        raise RuntimeError("full_system_backtest module is not imported")
    return module._SimClock


@dataclass(frozen=True)
class EvaluationCellSpec:
    """One tournament cell: strategy × symbol × params × cost × faults."""

    strategy_id: str
    symbol: str
    timeframe: str = "1h"
    params: Mapping[str, Any] = field(default_factory=dict)
    cost_scenario: CostScenario = SCENARIO_BASE
    fault: FaultProfile = FAULT_NONE

    def __post_init__(self) -> None:
        if not self.strategy_id or not self.symbol:
            raise ValueError("strategy_id and symbol are required")
        object.__setattr__(
            self, "params", MappingProxyType(dict(sorted(self.params.items())))
        )

    @property
    def params_hash(self) -> str:
        payload = json.dumps(dict(self.params), sort_keys=True, separators=(",", ":"))
        return hashlib.sha256(payload.encode()).hexdigest()[:12]

    @property
    def cell_id(self) -> str:
        safe_symbol = self.symbol.replace("/", "")
        base = (
            f"{self.strategy_id}__{safe_symbol}__{self.timeframe}"
            f"__{self.cost_scenario.name}__p{self.params_hash}"
        )
        if self.fault.active:
            base += f"__f{self.fault.name}"
        return base


def canonical_signal_series(
    adapter: LegacyDataFrameAdapter,
    frame: pl.DataFrame,
    *,
    warmup_bars: int,
    symbol: str,
    start_index: int = 0,
    end_index: int | None = None,
) -> list[int]:
    """Per-bar deterministic signals from the canonical contract.

    Signal at index j is decided on the bar closed at time[j] (window ends
    strictly before j) and is executed at bar j+1's open by the simulator —
    decision-on-closed-bar / execute-next-open (STR-0203).
    """
    if "time" not in frame.columns:
        raise ValueError("frame must carry a 'time' column")
    times = frame["time"].to_list()
    # Storage timestamps may be tz-naive; the contract requires awareness.
    if times and getattr(times[0], "tzinfo", None) is None:
        times = [value.replace(tzinfo=UTC) for value in times]
    if start_index < 0:
        raise ValueError("start_index must be non-negative")
    resolved_end = frame.height if end_index is None else min(end_index, frame.height)
    if resolved_end < 0:
        raise ValueError("end_index must be non-negative")
    signals = [0] * frame.height
    first_signal = max(warmup_bars + 1, start_index)
    for j in range(first_signal, resolved_end):
        observed_at = times[j]
        try:
            window = build_ohlcv_window(
                frame.head(j),
                observed_at=observed_at,
                bars=warmup_bars + 1,
            )
        except FeatureUnavailableError:
            continue  # insufficient history at this bar → stay flat
        row = frame.row(j, named=True)
        observation = _market_observation(symbol, observed_at, row, window)
        forecast = adapter.forecast(observation)
        action = forecast.metadata.get("canonical_action")
        if action == ACTION_BUY:
            signals[j] = 1
        elif action == ACTION_SELL:
            signals[j] = -1
    return signals


def _market_observation(strategy_id, observed_at, row, window):
    from trading_agent.research.forecast import MarketObservation

    return MarketObservation(
        symbol=strategy_id.split(":")[0],
        observed_at=observed_at,
        open=float(row["open"]),
        high=float(row["high"]),
        low=float(row["low"]),
        close=float(row["close"]),
        volume=float(row.get("volume", 0.0)),
        features={FEATURE_OHLCV_WINDOW: window},
    )


@dataclass(frozen=True)
class EvaluationArtifact:
    """Content-addressed result of one tournament cell (STR-0207)."""

    cell_id: str
    status: str  # COMPLETED | FAILED
    descriptor_id: str
    strategy_id: str
    symbol: str
    timeframe: str
    params_hash: str
    cost_scenario: str
    fault_profile: str
    commission: float
    slippage: float
    data_manifest_sha: str
    commit_sha: str
    report_path: str | None
    metrics: Mapping[str, Any]
    execution_health: Mapping[str, Any]
    failure_reasons: tuple[str, ...] = ()
    created_at: str = ""
    measurement_window: tuple[int, int] | None = None
    simulation_window: tuple[int, int | None] | None = None
    signal_delay_bars: int = 0
    selection_freeze_id: str | None = None
    execution_control: Mapping[str, Any] = field(default_factory=dict)

    @property
    def artifact_id(self) -> str:
        identity: dict[str, Any] = {
            "cell_id": self.cell_id,
            "status": self.status,
            "descriptor_id": self.descriptor_id,
            "strategy_id": self.strategy_id,
            "symbol": self.symbol,
            "timeframe": self.timeframe,
            "params_hash": self.params_hash,
            "cost_scenario": self.cost_scenario,
            "fault_profile": self.fault_profile,
            "commission": self.commission,
            "slippage": self.slippage,
            "data_manifest_sha": self.data_manifest_sha,
            "commit_sha": self.commit_sha,
            "report_path": self.report_path,
            "measurement_window": self.measurement_window,
            "simulation_window": self.simulation_window,
            "signal_delay_bars": self.signal_delay_bars,
            "selection_freeze_id": self.selection_freeze_id,
            "metrics": dict(self.metrics),
            "execution_health": dict(self.execution_health),
            "failure_reasons": self.failure_reasons,
        }
        # Preserve content IDs of artifacts created before STR-0208. New
        # isolated runs bind their execution-control policy and actual attempt
        # count into the evidence identity.
        if self.execution_control:
            identity["execution_control"] = dict(self.execution_control)
        payload = json.dumps(
            identity,
            sort_keys=True,
            separators=(",", ":"),
        )
        return f"sha256:{hashlib.sha256(payload.encode()).hexdigest()}"

    def to_dict(self) -> dict[str, Any]:
        return {
            "artifact_id": self.artifact_id,
            "cell_id": self.cell_id,
            "status": self.status,
            "descriptor_id": self.descriptor_id,
            "strategy_id": self.strategy_id,
            "symbol": self.symbol,
            "timeframe": self.timeframe,
            "params_hash": self.params_hash,
            "cost_scenario": self.cost_scenario,
            "fault_profile": self.fault_profile,
            "commission": self.commission,
            "slippage": self.slippage,
            "data_manifest_sha": self.data_manifest_sha,
            "commit_sha": self.commit_sha,
            "report_path": self.report_path,
            "metrics": dict(self.metrics),
            "execution_health": dict(self.execution_health),
            "failure_reasons": list(self.failure_reasons),
            "created_at": self.created_at,
            "measurement_window": list(self.measurement_window)
            if self.measurement_window is not None
            else None,
            "simulation_window": list(self.simulation_window)
            if self.simulation_window is not None
            else None,
            "signal_delay_bars": self.signal_delay_bars,
            "selection_freeze_id": self.selection_freeze_id,
            "execution_control": dict(self.execution_control),
        }

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> "EvaluationArtifact":
        """Rebuild and verify an artifact loaded from persistent evidence."""

        measurement = data.get("measurement_window")
        simulation = data.get("simulation_window")
        artifact = cls(
            cell_id=str(data.get("cell_id", "")),
            status=str(data.get("status", "FAILED")),
            descriptor_id=str(data.get("descriptor_id", "")),
            strategy_id=str(data.get("strategy_id", "")),
            symbol=str(data.get("symbol", "")),
            timeframe=str(data.get("timeframe", "")),
            params_hash=str(data.get("params_hash", "")),
            cost_scenario=str(data.get("cost_scenario", "")),
            fault_profile=str(data.get("fault_profile", "none")),
            commission=float(data.get("commission", 0.0)),
            slippage=float(data.get("slippage", 0.0)),
            data_manifest_sha=str(data.get("data_manifest_sha", "")),
            commit_sha=str(data.get("commit_sha", "")),
            report_path=data.get("report_path"),
            metrics=dict(data.get("metrics", {})),
            execution_health=dict(data.get("execution_health", {})),
            failure_reasons=tuple(data.get("failure_reasons", ())),
            created_at=str(data.get("created_at", "")),
            measurement_window=tuple(measurement) if measurement is not None else None,
            simulation_window=tuple(simulation) if simulation is not None else None,
            signal_delay_bars=int(data.get("signal_delay_bars", 0)),
            selection_freeze_id=data.get("selection_freeze_id"),
            execution_control=dict(data.get("execution_control", {})),
        )
        expected_id = data.get("artifact_id")
        if expected_id is not None and expected_id != artifact.artifact_id:
            raise ValueError("evaluation artifact content hash mismatch")
        return artifact


