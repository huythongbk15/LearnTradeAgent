"""Canonical strategy tournament (Phase S2).

Runs ``strategy × pair × parameters × cost-scenario`` cells through the
*same* full execution path as :mod:`scripts.full_system_backtest`
(ExecutionEngine authority chain, RiskController, protective orders,
lifecycle event store) with exactly one difference per cell: the signal
series is generated by the canonical
``ForecastStrategy.forecast(MarketObservation)`` contract via the
allowlisted, hash-verified registry — never by ad-hoc strategy code.

Fail-closed guarantees (STR-0208/0209):

- Only registry allowlisted strategies can be evaluated.
- Every cell writes to its own state dir / report path / manifest.
- A cell missing any required metric (or carrying non-finite values) is
  recorded as ``FAILED`` — missing evidence is NEVER defaulted to 0.
- Terminal-state hygiene is inherited from the simulator's
  ``execution_health`` block (unknown/manual/unprotected must all be zero).
- Per-cell timeout and retry policy enforced inside ``run_cell()`` (STR-0208).
  Cell failure is isolated and does not kill the matrix; errors are recorded
  as FAILED artifacts, never promoted to valid results.
"""

