# ── deterministic data ───────────────────────────────────────────────────


def _trend_df(
    base: float,
    *,
    n_flat: int = 45,
    n_trend: int = 34,
    growth: float = 1.008,
    start: datetime | None = None,
) -> pl.DataFrame:
    """Flat warmup then steady uptrend → exactly one MA10/30 bullish cross."""
    start = start or datetime(2024, 1, 1, tzinfo=UTC)
    prices = [base] * n_flat
    p = base
    for _ in range(n_trend):
        p *= growth
        prices.append(p)
    stamps = [start + timedelta(hours=i) for i in range(len(prices))]
    return pl.DataFrame(
        {
            "timestamp": stamps,
            "open": prices,
            "high": [x * 1.001 for x in prices],
            "low": [x * 0.999 for x in prices],
            "close": prices,
            "volume": [1000.0] * len(prices),
        }
    )


def _first_cross_index(df: pl.DataFrame, fast: int = 10, slow: int = 30) -> int:
    closes = df["close"].to_list()

    def ma(i: int, w: int) -> float:
        return sum(closes[i - w + 1 : i + 1]) / w

    for i in range(slow - 1, len(closes)):
        f_now, s_now = ma(i, fast), ma(i, slow)
        f_prev, s_prev = ma(i - 1, fast), ma(i - 1, slow)
        if f_prev <= s_prev and f_now > s_now:
            return i
    raise AssertionError("no bullish cross generated by fixture data")


