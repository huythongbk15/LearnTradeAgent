class TestBrokerPhaseAndReservations:
    def _flat_df(self, n: int = 8, price: float = 100.0) -> pl.DataFrame:
        start = datetime(2024, 1, 1, tzinfo=UTC)
        stamps = [start + timedelta(hours=i) for i in range(n)]
        return pl.DataFrame(
            {
                "timestamp": stamps,
                "open": [price] * n,
                "high": [price] * n,
                "low": [price] * n,
                "close": [price] * n,
                "volume": [10.0] * n,
            }
        )

    def _q(self, key, side, qty, dt, phase=None, ref=100.0, symbol="BTC/USDT"):
        from trading_agent.backtest.portfolio_backtest import QueuedOrder

        return QueuedOrder(
            idempotency_key=key,
            symbol=symbol,
            side=side,
            quantity=qty,
            reference_price=ref,
            decision_time=dt,
            **({"phase": phase} if phase else {}),
        )

    def test_reduction_settles_before_increase(self, config, stores, temp_dir):
        from trading_agent.backtest.portfolio_backtest import (
            HistoricalSimulationBroker,
        )

        rules = {"BTC/USDT": _instrument_rules("BTC/USDT")}
        eng = _build_engine(config, stores, temp_dir, rules)
        try:
            df = self._flat_df()
            pbt = PortfolioBacktestEngine(
                eng, bars={("BTC/USDT", "1h"): df}, initial_cash=100.0
            )
            broker = HistoricalSimulationBroker(100.0, fee_bps=10.0, slippage_bps=5.0)
            clock = pbt.clock
            dt = df["timestamp"][2]  # fills at bar[3] open

            # seed a long so the reduction SELL is fillable + frees cash
            broker.positions["BTC/USDT"] = {"qty": 1.0, "avg_px": 100.0}

            # INCREASE queued EARLIER but must settle AFTER the reduction
            broker.queue(self._q("b1", "buy", 1.0, dt))
            broker.queue(self._q("s1", "sell", 1.0, dt, phase="reduction"))

            fills = broker.settle(df["timestamp"][3], clock, [("BTC/USDT", "1h")])
            assert [f.side for f in fills] == ["sell", "buy"], (
                "REDUCTION must settle before INCREASE"
            )
            # freed sell cash made the buy affordable: cash stays positive
            assert broker.cash > 0
            assert broker.pending_count == 0
        finally:
            eng._graceful_shutdown()

    def test_reserved_cash_and_inventory_count_pending(self, config, stores, temp_dir):
        from trading_agent.backtest.portfolio_backtest import (
            HistoricalSimulationBroker,
        )

        rules = {"BTC/USDT": _instrument_rules("BTC/USDT")}
        eng = _build_engine(config, stores, temp_dir, rules)
        try:
            df = self._flat_df()
            pbt = PortfolioBacktestEngine(
                eng, bars={("BTC/USDT", "1h"): df}, initial_cash=100.0
            )
            broker = HistoricalSimulationBroker(100.0, fee_bps=10.0, slippage_bps=5.0)
            dt = df["timestamp"][2]
            broker.queue(self._q("b1", "buy", 2.0, dt, ref=50.0))
            broker.queue(self._q("s1", "sell", 0.5, dt))

            est_notional = 2.0 * 50.0
            expected_reserved = est_notional * (1 + 10.0 / 10_000.0 + 5.0 / 10_000.0)
            assert broker.reserved_cash() == pytest.approx(expected_reserved)
            assert broker.reserved_inventory("BTC/USDT") == pytest.approx(0.5)
            assert broker.reserved_inventory("ETH/USDT") == 0.0

            # nothing eligible to fill yet (settle BEFORE dt's next bar)
            fills = broker.settle(df["timestamp"][2], pbt.clock, [("BTC/USDT", "1h")])
            assert fills == []
            # reservations persist while orders stay queued
            assert broker.reserved_cash() == pytest.approx(expected_reserved)
        finally:
            eng._graceful_shutdown()

    def test_snapshot_reflects_reservations(self, config, stores, temp_dir):
        """Snapshot must hide reserved inventory/cash from decisions while
        marking equity on FULL holdings."""
        from trading_agent.authority.config import Environment
        from trading_agent.authority.portfolio import ReconciliationState as RS
        from trading_agent.backtest.portfolio_backtest import (
            HistoricalSimulationBroker,
        )

        rules = {"BTC/USDT": _instrument_rules("BTC/USDT")}
        eng = _build_engine(config, stores, temp_dir, rules)
        try:
            df = self._flat_df(price=200.0)
            pbt = PortfolioBacktestEngine(
                eng, bars={("BTC/USDT", "1h"): df}, initial_cash=100.0
            )
            broker = HistoricalSimulationBroker(100.0)
            broker.cash = 50_000.0
            broker.positions["BTC/USDT"] = {"qty": 2.0, "avg_px": 200.0}
            dt = df["timestamp"][2]
            broker.queue(self._q("s1", "sell", 0.5, dt, phase="reduction"))
            broker.queue(self._q("b1", "buy", 1.0, dt, ref=200.0))

            snap = pbt._build_snapshot(df["timestamp"][4], broker, Environment.PAPER)

            # effective inventory = held − pending sell
            assert snap.positions["BTC/USDT"] == pytest.approx(1.5)
            # equity marked on FULL held qty at last close
            assert snap.equity == pytest.approx(50_000.0 + 2.0 * 200.0)
            # available cash net of pending-buy reservation
            expected_reserved = 1.0 * 200.0 * (1 + 10e-4 + 5e-4)
            assert snap.available_cash == pytest.approx(50_000.0 - expected_reserved)
            assert snap.reserved_cash == pytest.approx(expected_reserved)
            assert snap.reserved_inventory == pytest.approx(0.5)
            # exposure computed off EFFECTIVE qty
            assert snap.symbol_exposures["BTC/USDT"] == pytest.approx(
                1.5 * 200.0 / snap.equity
            )
            assert snap.reconciliation_state is RS.RECONCILED
        finally:
            eng._graceful_shutdown()


# ── Actual-fill safety guards (P0 execution safety) ──────────────────────


class TestBrokerFillSafetyGuards:
    """Guarantees on ACTUAL fills (not planning reservations):
    no negative cash, no synthetic proceeds, aggregate-spend safety,
    reservation-estimate < actual-cost determinism."""

    def _df(self, levels, n_gap=2, base_open=100.0):
        """Bars: flat at 100 then GAP to ``levels`` on bar[gap_index]."""
        start = datetime(2024, 1, 1, tzinfo=UTC)
        prices = [base_open] * n_gap + levels
        # ensure unique open timestamps, ascending
        stamps = [start + timedelta(hours=i) for i in range(len(prices))]
        return pl.DataFrame(
            {
                "timestamp": stamps,
                "open": prices,
                "high": prices,
                "low": prices,
                "close": prices,
                "volume": [10.0] * len(prices),
            }
        )

    def _setup(self, config, stores, temp_dir, prices_df, cash):
        from trading_agent.backtest.portfolio_backtest import (
            HistoricalSimulationBroker,
        )

        rules = {"BTC/USDT": _instrument_rules("BTC/USDT")}
        eng = _build_engine(config, stores, temp_dir, rules)
        pbt = PortfolioBacktestEngine(
            eng, bars={("BTC/USDT", "1h"): prices_df}, initial_cash=100.0
        )
        broker = HistoricalSimulationBroker(cash, fee_bps=10.0, slippage_bps=5.0)
        return eng, pbt, broker

    def _q(self, key, side, qty, dt, phase=None, ref=100.0):
        from trading_agent.backtest.portfolio_backtest import QueuedOrder

        return QueuedOrder(
            idempotency_key=key,
            symbol="BTC/USDT",
            side=side,
            quantity=qty,
            reference_price=ref,
            decision_time=dt,
            phase=phase,
        )

    def test_gap_up_buy_never_negative_cash(self, config, stores, temp_dir):
        df = self._df(levels=[200.0, 200.0], n_gap=2, base_open=100.0)
        eng, pbt, broker = self._setup(config, stores, temp_dir, df, cash=105.0)
        try:
            # reserve-based estimate ~100.15 fit; ACTUAL gap open=200 ⇒ cost ~201
            broker.queue(self._q("buy1", "buy", 1.0, df["timestamp"][2], ref=100.0))
            fills = broker.settle(df["timestamp"][3], pbt.clock, [("BTC/USDT", "1h")])
            assert fills == []  # rejected
            assert broker.cash == pytest.approx(105.0)  # untouched
            assert broker.pending_count == 0  # DROPPED permanently
            assert broker.reserved_cash() == 0.0
            assert broker.cash >= 0.0
        finally:
            eng._graceful_shutdown()

    def test_oversized_sell_no_synthetic_proceeds(self, config, stores, temp_dir):
        # 4 flat bars at 100; SELL 5 lots but only hold 1
        df = self._df(levels=[100.0, 100.0, 100.0, 100.0], n_gap=0, base_open=100.0)
        eng, pbt, broker = self._setup(config, stores, temp_dir, df, cash=1.0)
        try:
            broker.positions["BTC/USDT"] = {"qty": 1.0, "avg_px": 100.0}
            # queue SELL 5.0 at bar[2] open (decision_time=bar1)
            broker.queue(
                self._q("s1", "sell", 5.0, df["timestamp"][1], phase="reduction")
            )
            fills = broker.settle(df["timestamp"][2], pbt.clock, [("BTC/USDT", "1h")])
            assert len(fills) == 1
            f = fills[0]
            assert f.quantity == pytest.approx(1.0)  # capped to held
            # proceeds ONLY from 1 lot (sell proceeds minus fee), no synthetic
            raw = 100.0
            price = raw * (1 - 0.0005)
            expected_proceeds = price - price * 0.001
            assert broker.cash == pytest.approx(1.0 + expected_proceeds)
            assert broker.positions["BTC/USDT"]["qty"] == pytest.approx(0.0)
            assert broker.pending_count == 0  # remainder discarded
        finally:
            eng._graceful_shutdown()

    def test_two_buys_same_fill_timestamp_aggregate(self, config, stores, temp_dir):
        # df: [100,100,100], 3 hourly bars; fill at ts[2]
        df = self._df(levels=[100.0, 100.0], n_gap=1, base_open=100.0)
        # cost each: 1*100*1.0005 + fee(1*100*1.0005*0.001) ≈ 100.15005
        cash = 100.15005 + 0.01  # covers exactly one
        eng, pbt, broker = self._setup(config, stores, temp_dir, df, cash=cash)
        try:
            broker.queue(self._q("b1", "buy", 1.0, df["timestamp"][1], ref=100.0))
            broker.queue(self._q("b2", "buy", 1.0, df["timestamp"][1], ref=100.0))
            fills = broker.settle(df["timestamp"][2], pbt.clock, [("BTC/USDT", "1h")])
            assert len(fills) == 1
            assert fills[0].idempotency_key == "b1"
            raw = 100.0
            price = raw * (1 + 0.0005)  # BUY slips up
            one_buy_cost = price + price * 0.001  # notional + fee
            expected_cash = cash - one_buy_cost
            assert broker.cash == pytest.approx(expected_cash, abs=1e-9)
            assert broker.cash >= 0.0
            assert broker.pending_count == 0  # second DROPPED permanently
        finally:
            eng._graceful_shutdown()

    def test_reservation_undershoot_actual_cost_deterministic(
        self, config, stores, temp_dir
    ):
        """Reservation estimate (ref price based) < actual fill cost (gap)
        ⇒ guard rejects deterministically, cash never negative."""
        df = self._df(levels=[105.0, 105.0], n_gap=2, base_open=100.0)
        eng, pbt, broker = self._setup(config, stores, temp_dir, df, cash=101.0)
        try:
            # reservation estimate: 1*100*(1+slip+fee) ≈ 100.15 → snapshot
            # available_cash = 101 − 100.15 > 0 ⇒ planning APPROVES.
            # ACTUAL: 1*105*1.005 + fee ≈ 105.78 > 101 ⇒ guard rejects.
            broker.queue(self._q("buy1", "buy", 1.0, df["timestamp"][2], ref=100.0))
            reserved = broker.reserved_cash()
            assert reserved == pytest.approx(100.0 * 1.0015)  # ~100.15
            assert (101.0 - reserved) > 0  # planning approves
            fills = broker.settle(df["timestamp"][3], pbt.clock, [("BTC/USDT", "1h")])
            assert fills == []
            assert broker.cash == pytest.approx(101.0)
            assert broker.positions.get("BTC/USDT", {}).get("qty", 0.0) == 0.0
        finally:
            eng._graceful_shutdown()


# ── Order rejection = permanent drop (P0 safety) ─────────────────────────


class TestBrokerRejectionDrop:
    """Rejected orders are DROPPED permanently, not re-queued.
    Covers: gap-up BUY drop, stale rejected BUY never fills on price drop,
    zero-inventory SELL drop, stale rejected SELL never touches new inventory."""

    def _df_flat(self, n: int = 8, price: float = 100.0) -> pl.DataFrame:
        start = datetime(2024, 1, 1, tzinfo=UTC)
        stamps = [start + timedelta(hours=i) for i in range(n)]
        return pl.DataFrame(
            {
                "timestamp": stamps,
                "open": [price] * n,
                "high": [price] * n,
                "low": [price] * n,
                "close": [price] * n,
                "volume": [10.0] * n,
            }
        )

    def _df_gap(self, levels, n_gap=2, base_open=100.0):
        start = datetime(2024, 1, 1, tzinfo=UTC)
        prices = [base_open] * n_gap + levels
        stamps = [start + timedelta(hours=i) for i in range(len(prices))]
        return pl.DataFrame(
            {
                "timestamp": stamps,
                "open": prices,
                "high": prices,
                "low": prices,
                "close": prices,
                "volume": [10.0] * len(prices),
            }
        )

    def _setup(self, config, stores, temp_dir, df, cash):
        rules = {"BTC/USDT": _instrument_rules("BTC/USDT")}
        eng = _build_engine(config, stores, temp_dir, rules)
        pbt = PortfolioBacktestEngine(
            eng, bars={("BTC/USDT", "1h"): df}, initial_cash=100.0
        )
        broker = HistoricalSimulationBroker(cash, fee_bps=10.0, slippage_bps=5.0)
        return eng, pbt, broker

    def _q(self, key, side, qty, dt, phase=None, ref=100.0):
        return QueuedOrder(
            idempotency_key=key,
            symbol="BTC/USDT",
            side=side,
            quantity=qty,
            reference_price=ref,
            decision_time=dt,
            phase=phase,
        )

    def test_gap_up_buy_dropped_not_queued(self, config, stores, temp_dir):
        """Gap-up BUY rejected → pending_count == 0, reserved_cash == 0."""
        # flat 100 then GAP to 200 at bar[2]
        df = self._df_gap(levels=[200.0, 200.0], n_gap=2, base_open=100.0)
        # cash only ~105, actual cost ~201
        eng, pbt, broker = self._setup(config, stores, temp_dir, df, cash=105.0)
        try:
            # decision at bar[2] (gap bar open), fill would be at bar[2] open=200
            broker.queue(self._q("buy1", "buy", 1.0, df["timestamp"][2], ref=100.0))
            assert broker.pending_count == 1
            fills = broker.settle(df["timestamp"][3], pbt.clock, [("BTC/USDT", "1h")])
            assert fills == []  # rejected
            assert broker.pending_count == 0  # DROPPED
            assert broker.reserved_cash() == 0.0
            assert broker.cash == pytest.approx(105.0)
        finally:
            eng._graceful_shutdown()

    def test_rejected_buy_never_fills_on_price_drop(self, config, stores, temp_dir):
        """Rejected BUY + later price drop → old order NEVER fills."""
        df = self._df_gap(levels=[200.0, 90.0, 90.0, 90.0], n_gap=2, base_open=100.0)
        # first gap UP to 200 (rejects), then drop to 90
        eng, pbt, broker = self._setup(config, stores, temp_dir, df, cash=105.0)
        try:
            # decision at bar[2] (gap bar open=200), fill at bar[2] → rejected
            broker.queue(self._q("buy1", "buy", 1.0, df["timestamp"][2], ref=100.0))
            fills = broker.settle(df["timestamp"][3], pbt.clock, [("BTC/USDT", "1h")])
            assert fills == []
            assert broker.pending_count == 0  # dropped

            # later: price dropped to 90 at bar[3]; old order must NOT fill
            fills2 = broker.settle(df["timestamp"][4], pbt.clock, [("BTC/USDT", "1h")])
            assert fills2 == []
            assert broker.positions.get("BTC/USDT", {}).get("qty", 0.0) == 0.0
            assert broker.cash == pytest.approx(105.0)
        finally:
            eng._graceful_shutdown()

    def test_zero_inventory_sell_dropped(self, config, stores, temp_dir):
        """SELL with zero inventory rejected → pending_count == 0."""
        df = self._df_flat()
        eng, pbt, broker = self._setup(config, stores, temp_dir, df, cash=1.0)
        try:
            broker.queue(
                self._q("s1", "sell", 5.0, df["timestamp"][1], phase="reduction")
            )
            assert broker.pending_count == 1
            fills = broker.settle(df["timestamp"][2], pbt.clock, [("BTC/USDT", "1h")])
            assert fills == []
            assert broker.pending_count == 0  # DROPPED
            assert broker.reserved_inventory("BTC/USDT") == 0.0
            assert broker.cash == pytest.approx(1.0)
        finally:
            eng._graceful_shutdown()

    def test_rejected_sell_never_touches_new_inventory(self, config, stores, temp_dir):
        """Rejected old SELL + later new BUY position → stale SELL NEVER touches new inventory."""
        df = self._df_flat()
        eng, pbt, broker = self._setup(config, stores, temp_dir, df, cash=500.0)
        try:
            # queue SELL with NO inventory → rejected & dropped
            broker.queue(
                self._q("s1", "sell", 5.0, df["timestamp"][1], phase="reduction")
            )
            fills = broker.settle(df["timestamp"][2], pbt.clock, [("BTC/USDT", "1h")])
            assert fills == []
            assert broker.pending_count == 0  # dropped

            # later: BUY builds a new position
            broker.queue(self._q("b1", "buy", 3.0, df["timestamp"][2]))
            fills = broker.settle(df["timestamp"][3], pbt.clock, [("BTC/USDT", "1h")])
            assert len(fills) == 1
            assert fills[0].side == "buy"
            assert fills[0].quantity == pytest.approx(3.0)

            # old rejected SELL must NOT touch the new 3.0 inventory
            # (it was dropped, so no more orders queued)
            assert broker.pending_count == 0
            assert broker.positions["BTC/USDT"]["qty"] == pytest.approx(3.0)

            # even if we manually settle again, nothing happens
            fills2 = broker.settle(df["timestamp"][4], pbt.clock, [("BTC/USDT", "1h")])
            assert fills2 == []
            assert broker.positions["BTC/USDT"]["qty"] == pytest.approx(3.0)
        finally:
            eng._graceful_shutdown()
