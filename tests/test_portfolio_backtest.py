# ── DoD: PortfolioBacktestEngine exists + N=1 parity ─────────────────────


class TestN1Parity:
    def test_single_binding_full_ledger_math_and_no_lookahead(
        self, config, stores, temp_dir
    ):

        rules = {"BTC/USDT": _instrument_rules("BTC/USDT")}
        eng = _build_engine(config, stores, temp_dir, rules)
        try:
            promotion_store, artifact_store = stores
            art = _make_artifact(
                artifact_store,
                promotion_store,
                symbol="BTC/USDT",
                timeframe="1h",
                fast=10,
                slow=30,
            )
            _promote(None, promotion_store, art)

            df = _trend_df(60_000.0)
            pbt = PortfolioBacktestEngine(
                eng, bars={("BTC/USDT", "1h"): df}, initial_cash=100_000.0
            )
            result = pbt.run("paper")

            # exactly ONE position-opening trade (crossover fires once)
            buys = [t for t in result.trades if t.side == "buy"]
            assert len(buys) == 1
            buy = buys[0]

            # ── no lookahead: decision uses close[t], fill = open[t+1] ──
            cross_i = _first_cross_index(df)
            decision_expected = df["timestamp"][cross_i].replace(
                tzinfo=UTC
            ) + timedelta(seconds=TF_SEC)
            assert buy.decision_time == decision_expected

            open_next = float(df["open"][cross_i + 1])
            slip = 5.0 / 10_000.0
            assert buy.price == pytest.approx(open_next * (1.0 + slip), rel=1e-12)
            assert buy.fill_time > buy.decision_time  # earliest t+1

            # ── shared-ledger parity, recomputed independently ──
            fee_rate = 10.0 / 10_000.0
            cost = buy.notional + buy.fee
            cash_after_buy = 100_000.0 - cost
            qty = buy.quantity
            final_close = float(df["close"][-1])
            expected_final = cash_after_buy + qty * final_close
            assert result.final_equity == pytest.approx(expected_final, rel=1e-9)

            # equity curve monotone bookkeeping: starts ≈ initial, ends final
            assert result.equity_curve[0][1] == pytest.approx(100_000.0, rel=1e-9)
            assert result.equity_curve[-1][1] == pytest.approx(expected_final, rel=1e-9)

            # promoted artifact actually resolved through the chain
            assert buy.idempotency_key
            # contribution: mtm gain − costs, matches final−initial for N=1
            contrib = result.per_symbol_contribution.get("BTC/USDT")
            assert contrib is not None
            assert result.final_equity - 100_000.0 == pytest.approx(contrib, rel=1e-6)
        finally:
            eng._graceful_shutdown()

    def test_signal_uses_closed_bar_not_forming_bar(self, config, stores, temp_dir):
        """The decision at time t must never see bar t itself (only < t)."""

        rules = {"BTC/USDT": _instrument_rules("BTC/USDT")}
        eng = _build_engine(config, stores, temp_dir, rules)
        try:
            promotion_store, artifact_store = stores
            art = _make_artifact(
                artifact_store,
                promotion_store,
                symbol="BTC/USDT",
                timeframe="1h",
                fast=10,
                slow=30,
            )
            _promote(None, promotion_store, art)
            df = _trend_df(60_000.0)
            clock_bars = {("BTC/USDT", "1h"): df}
            pbt = PortfolioBacktestEngine(eng, bars=clock_bars, initial_cash=100_000.0)
            cross_i = _first_cross_index(df)
            decision_close_ts = df["timestamp"][cross_i].replace(
                tzinfo=UTC
            ) + timedelta(hours=1)
            sl = pbt.clock.slice_upto(("BTC/USDT", "1h"), decision_close_ts)
            # last row IS the signal bar (closed at t); nothing beyond it
            assert sl["timestamp"][-1] == df["timestamp"][cross_i]
            assert len(sl) == cross_i + 1
        finally:
            eng._graceful_shutdown()


